@pytest.mark.parametrize("target", sorted(SAMPLES))
def test_parse_and_fingerprint(target):
    s = SAMPLES[target]
    hello = fc.parse_client_hello(bytes.fromhex(s["hex"]))
    assert hello["record_version"] == "0301"
    assert hello["legacy_version"] == "0303"
    assert hello["session_id_len"] == 32
    assert hello["handshake_length"] == s["handshake_length"]
    assert sum(1 for c in hello["cipher_suites"] if not c.get("grease")) == s["cipher_count"]
    assert sum(1 for e in hello["extensions"] if not e["grease"]) == s["ext_count"]
    fp = fc.fingerprints(hello)
    assert fp["ja3_hash"] == s["ja3_hash"]
    assert fp["ja4"] == s["ja4"]
    assert fp["ja4_r"] == s["ja4_r"]


def test_ja3_matches_peet_sample_for_chrome150():
    # The extension order peet.ws reported for curl_cffi chrome150 in one
    # connection; the Chrome family permutes per connection so this is a
    # check of the JA3 computation, not of a stable per-target value.
    exts = [45, 0xFF01, 16, 11, 43, 51, 0, 27, 5, 10, 0xFE0D, 35, 13, 0x44CD, 18, 23]
    ciphers = [0x1301, 0x1302, 0x1303, 0xC02B, 0xC02F, 0xC02C, 0xC030, 0xCCA9, 0xCCA8,
               0xC013, 0xC014, 0x009C, 0x009D, 0x002F, 0x0035]
    text = "771,%s,%s,4588-29-23-24,0" % ("-".join(map(str, ciphers)), "-".join(map(str, exts)))
    assert hashlib.md5(text.encode()).hexdigest() == "e2a070130f888c31d5b457a9266b4ef9"


def test_grease_detection():
    assert fc.is_grease(0x0A0A) and fc.is_grease(0xFAFA) and fc.is_grease(0x8A8A)
    assert not fc.is_grease(0x0A1A) and not fc.is_grease(0x1301)


def test_chrome_key_share_and_ech_decode():
    hello = fc.parse_client_hello(bytes.fromhex(SAMPLES["chrome150"]["hex"]))
    ks = fc._ext_by_type(hello, 51)["decoded"]["shares"]
    assert [(s.get("name"), s["key_length"]) for s in ks] == [("GREASE", 1), ("X25519MLKEM768", 1216), ("x25519", 32)]
    ech = fc._ext_by_type(hello, 0xFE0D)["decoded"]
    assert ech["type_name"] == "outer" and ech["kdf_name"] == "HKDF-SHA256" and ech["aead_name"] == "AES-128-GCM"
    assert ech["enc_len"] == 32 and ech["payload_len"] in (144, 176, 208, 240)
    assert hello["extensions"][0]["grease"] and hello["extensions"][-1]["grease"]
    assert hello["extensions"][-1]["length"] == 1


def test_firefox_has_no_grease_and_fixed_order():
    hello = fc.parse_client_hello(bytes.fromhex(SAMPLES["firefox147"]["hex"]))
    assert not any(e["grease"] for e in hello["extensions"])
    assert not any(c.get("grease") for c in hello["cipher_suites"])
    order = [e["type"] for e in hello["extensions"]]
    assert order == [0, 23, 0xFF01, 10, 11, 35, 16, 5, 34, 18, 51, 43, 13, 45, 28, 27, 0xFE0D]
    assert fc._ext_by_type(hello, 28)["decoded"]["limit"] == 16385
